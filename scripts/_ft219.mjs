import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import puppeteer from 'puppeteer-core';
const ROOT = '/home/keromanix/dev/agent-office/data/worktrees/swze96/FT-219';
const port = 7600 + Math.floor(Math.random() * 100);
const srv = spawn(process.execPath, ['server/index.js'], { cwd: ROOT, env: { ...process.env, AO_PORT: String(port), AO_TEST_ALLOW_UNLINKED: '1', AO_DATA_DIR: fs.mkdtempSync(os.tmpdir() + '/ao219-') }, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const chrome = ['/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'].find((c) => fs.existsSync(c));
const b = await puppeteer.launch({ executablePath: chrome, headless: true, args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 1280, height: 720 });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const base = `http://127.0.0.1:${port}/`;
await p.goto(base + '?view=agents', { waitUntil: 'load' });
await new Promise((r) => setTimeout(r, 1500));
const navHas = await p.$eval('#sidebar', (s) => s.textContent.includes('Marketplace'));
console.log('menu con Marketplace:', navHas);
await p.click('[data-action="open-marketplace"]');
await new Promise((r) => setTimeout(r, 1500));
console.log('mp visible:', await p.$eval('#view-marketplace', (v) => !v.hidden), 'tabs', await p.$$eval('[data-mp-tab]', (a) => a.length), 'nav activo', await p.$eval('.nav-item.active', (a) => a.dataset.tab));
await p.screenshot({ path: '/tmp/ft219-mp.png' });
await p.goto(base, { waitUntil: 'load' });
await new Promise((r) => setTimeout(r, 1500));
console.log('recarga mp visible:', await p.$eval('#view-marketplace', (v) => !v.hidden));
await p.click('[data-action="back-agents"]');
await new Promise((r) => setTimeout(r, 800));
console.log('vuelta agents:', await p.$eval('#view-agents', (v) => !v.hidden));
await p.screenshot({ path: '/tmp/ft219-agents.png' });
await p.goto(base + '?view=marketplace', { waitUntil: 'load' });
await new Promise((r) => setTimeout(r, 1500));
console.log('view=marketplace:', await p.$eval('#view-marketplace', (v) => !v.hidden));
console.log('errores:', errs);
await b.close(); srv.kill();
